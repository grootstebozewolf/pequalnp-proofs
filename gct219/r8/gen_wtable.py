"""Witness table for orbit exclusion: pivot sets as n-bit masks (bit c = cell (c//q, c%q)), omega(I) = mask value (colex Σ2^pos).
Every d-subset mask is either a rep (no (σ,τ) lowers it) or gets one (σ,τ) with mask(hI) < mask(I). Emits a core-Lean file with
a Bool checker proved by `decide`-free kernel evaluation (`rfl` on a Bool)."""
import itertools, sys, json, numpy as np, time; sys.set_int_max_str_digits(0)
p, q, d = map(int, sys.argv[1:4]); n = p * q
RP = list(itertools.permutations(range(p))); CP = list(itertools.permutations(range(q)))
H = np.array([[rp[c // q] * q + cp[c % q] for c in range(n)] for rp in RP for cp in CP], dtype=np.int64)
P2 = (1 << np.arange(n)).astype(np.int64)
rows = []; reps = []
for K in itertools.combinations(range(n), d):
    m = sum(1 << c for c in K)
    v = P2[H[:, list(K)]].sum(axis=1); k = int(v.argmin())
    if v[k] < m: rows.append((m, k // len(CP), k % len(CP)))
    else: rows.append((m, -1, -1)); reps.append(K)
rows.sort()
O = json.load(open(f"orbitw_exp_{p}x{q}_d{d}.json")); orep = sorted(tuple(o["S"]) for o in O)
print(f"{p}x{q} d{d}: subsets {len(rows)}, reps {len(reps)} (orbitw: {len(orep)}, equal: {sorted(reps) == orep})")
L = lambda xs: "[" + ",".join(map(str, xs)) + "]"
NH = len(RP) * len(CP)
DG = [NH if a < 0 else a * len(CP) + b for m, a, b in rows]
CH = [DG[i:i+1000] for i in range(0, len(DG), 1000)]
chunks = "\n".join(f"def c{i} : List Nat := {L(c)}" for i, c in enumerate(CH))
src = f"""/-! Orbit-exclusion witness table for {p}x{q}, d = {d} (generated by r8/gen_wtable.py). Core Lean only.
Pivot sets = {n}-bit masks, omega(I) = mask value (colex). The table is a list of digits (chunks of 1000): digit k belongs to the k-th
d-subset in increasing order; digit = σ-index * {len(CP)} + τ-index of a lowering (σ,τ), or {NH} for an orbit representative. -/
set_option maxRecDepth 1000000
set_option maxHeartbeats 0
namespace WT{p}{q}{d}
def q : Nat := {q}
def rowPerms : List (List Nat) := {L([L(r) for r in RP])}
def colPerms : List (List Nat) := {L([L(c) for c in CP])}
def act (σ τ : List Nat) (m : Nat) : Nat :=
  (List.range {n}).foldl (fun acc c => if m.testBit c then acc + 2 ^ (σ.getD (c / q) 0 * q + τ.getD (c % q) 0) else acc) 0
/-- all d-subsets of range n as masks; increasing by construction (first block < 2^n <= second block) -/
def subsets : Nat → Nat → List Nat
  | _, 0 => [0]
  | 0, _ + 1 => []
  | n + 1, k + 1 => (subsets n (k + 1)) ++ ((subsets n k).map (· + 2 ^ n))
{chunks}
def digits : List Nat := {" ++ ".join(f"c{i}" for i in range(len(CH)))}
def okH (h m : Nat) : Bool := h == {NH} || decide (act (rowPerms.getD (h / {len(CP)}) []) (colPerms.getD (h % {len(CP)}) []) m < m)
def go : List Nat → List Nat → Nat → Bool
  | [], [], r => r == {len(reps)}
  | m :: ms, h :: hs, r => okH h m && go ms hs (if h == {NH} then r + 1 else r)
  | _, _, _ => false
def check : Bool := go (subsets {n} {d}) digits 0
theorem check_ok : check = true := by decide +kernel
end WT{p}{q}{d}
#print axioms WT{p}{q}{d}.check_ok
"""
open(f"r8/lean/WT{p}{q}{d}.lean", "w").write(src)
