"""Emit lean/PEqualNP/Gct/Scratch219/VJCore.lean from certs.json.

For every support S (32 lemmas `case_<bits>`, bit i = 1 iff i in S) the emitted proof:
  1. derives the dependent coordinates from the hypotheses (`linear_combination`, kappa);
  2. shows the free coordinates vanish together only at 0;
  3. takes a chart from `chart` and splits on the 3-set C;
  4. per chart: evaluates the cubic hypothesis M at the certificate's points and closes
     `1 = 0` by `linear_combination` with the certificate's cofactors.
Nothing here is trusted: Lean re-checks every step."""
import json, sys, itertools
import sympy as sp

certs = json.load(open(sys.argv[1] if len(sys.argv) > 1 else 'certs.json'))
OUT = sys.argv[2] if len(sys.argv) > 2 else '../lean/PEqualNP/Gct/Scratch219/VJCore.lean'

def coeff_str(c):
    c = sp.Rational(c)
    if c.q == 1: return f'({c.p} : ℂ)'
    return f'(({c.p} : ℂ) / {c.q})'

def poly_str(e, atom):
    """Lean text for a polynomial with rational coefficients; atom maps a sympy symbol to Lean."""
    e = sp.expand(sp.sympify(e))
    if e == 0: return '0'
    syms = sorted(e.free_symbols, key=str)
    if not syms: return coeff_str(e)
    p = sp.Poly(e, *syms)
    terms = []
    for mon, c in p.terms():
        fac = [coeff_str(c)]
        for s, k in zip(syms, mon):
            fac += [atom(s)] * k
        terms.append(' * '.join(fac))
    return ' + '.join(terms)

def bits(S): return ''.join('1' if i in S else '0' for i in range(5))

def kappa(S, free, a, b):
    A = sp.symbols('A0:5'); B = sp.symbols('B0:5')
    cs = [('hb', sum(B))] + [(f'h{i}', 2*A[i] - sum(A)) if i in S else (f'h{i}', B[i]) for i in range(5)]
    t = sp.symbols(f't0:{len(free)}')
    coord = {('a', i): A[i] for i in range(5)}; coord.update({('b', i): B[i] for i in range(5)})
    back = {t[n]: coord[tuple(f)] for n, f in enumerate(free)}
    out = {}
    for kind, vec in (('a', a), ('b', b)):
        for i in range(5):
            if [kind, i] in free: continue
            expr = sp.sympify(vec[i])
            target = sp.expand(coord[(kind, i)] - expr.subs(back))
            ks = sp.symbols(f'k0:{len(cs)}')
            comb = sp.expand(sum(kk*c for kk, (_, c) in zip(ks, cs)) - target)
            sol = sp.solve(sp.Poly(comb, *(list(A) + list(B))).coeffs(), ks, dict=True)[0]
            kv = {name: sp.sympify(sol.get(kk, 0)).subs({x: 0 for x in ks}) for kk, (name, _) in zip(ks, cs)}
            kv = {n: v for n, v in kv.items() if v != 0}
            # re-verify the combination exactly
            assert sp.expand(sum(kv.get(n, 0)*c for n, c in cs) - target) == 0
            out[(kind, i)] = (expr, kv)
    return out

L = []
w = L.append
w('import PEqualNP.Gct.Scratch219.VJChart')
w('')
w('/-! Generated by `gct219-vJ/genlean.py` from `gct219-vJ/certs.json`. Do not edit.')
w('')
w('The finite core of case vJ of L-gct-219: for each support `S` (bit `i` of the name is `1`')
w('iff `2 a i = ∑ a`, else `b i = 0`), a space `P` of dimension at least three on which `∑ b = 0`')
w('and the five cubics vanish cannot exist. Each chart is refuted by an explicit identity')
w('`1 = ∑ gᵢ Eᵢ` whose `Eᵢ` are values of the cubic hypothesis at combinations of chart vectors. -/')
w('')
w('namespace PEqualNP.Gct.Scratch219.VJ')
w('')
w('set_option linter.unusedSimpArgs false')
w('')
w('open Module Finset')
w('')
w('variable {P : Type*} [AddCommGroup P] [Module ℂ P] [FiniteDimensional ℂ P]')
w('')

by_S = {}
for c in certs: by_S.setdefault(tuple(c['S']), []).append(c)

SUM5 = lambda f: ' + '.join(f'{f} {i} x' for i in range(5))

for S, cs in sorted(by_S.items(), key=lambda kv: bits(kv[0])):
    c0 = cs[0]; free = c0['free']; N = len(free)
    name = f'case_{bits(S)}'
    hyps = []
    for i in range(5):
        hyps.append(f'(h{i} : ∀ x, 2 * a {i} x = ∑ j, a j x)' if i in S else f'(h{i} : b {i} = 0)')
    w(f'set_option maxHeartbeats 2000000 in')
    w(f'theorem {name} (a b : Fin 5 → P →ₗ[ℂ] ℂ)')
    w(f'    (E : ∀ x, (∀ i, a i x = 0) → (∀ i, b i x = 0) → x = 0)')
    w(f'    (hb : ∀ x, ∑ j, b j x = 0)')
    w('    ' + ' '.join(hyps))
    w(f'    (M : ∀ x j, g3 j (fun i => a i x) + g3 j (fun i => b i x) = 0)')
    w(f'    (hP : 2 < finrank ℂ P) : False := by')
    w(f'  have hb\' : ∀ x, {SUM5("b")} = 0 := fun x => by')
    w(f'    simpa only [Fin.sum_univ_five] using hb x')
    for i in range(5):
        if i in S:
            w(f'  have h{i}\' : ∀ x, 2 * a {i} x = {SUM5("a")} := fun x => by')
            w(f'    simpa only [Fin.sum_univ_five] using h{i} x')
        else:
            w(f'  have h{i}\' : ∀ x, b {i} x = 0 := fun x => by rw [h{i}]; rfl')
    t = sp.symbols(f't0:{N}')
    lean_free = [f'{k} {i}' for k, i in free]
    ks = kappa(S, free, c0['a'], c0['b'])
    dep_names = []
    for (kind, i), (expr, kv) in sorted(ks.items()):
        rhs = poly_str(expr, lambda s: f'{lean_free[int(str(s)[1:])]} x')
        comb = ' + '.join(f'{coeff_str(v)} * {n}\' x' for n, v in kv.items()) or '0'
        w(f'  have d{kind}{i} : ∀ x, {kind} {i} x = {rhs} := fun x => by')
        w(f'    linear_combination {comb}')
        dep_names.append(f'd{kind}{i}')
    tau = '(![' + ', '.join(lean_free) + f'] : Fin {N} → P →ₗ[ℂ] ℂ)'
    w(f'  have inj : ∀ x, (∀ k, {tau} k x = 0) → x = 0 := by')
    w(f'    intro x hx')
    for n, f in enumerate(lean_free):
        w(f'    have t{n} : {f} x = 0 := by simpa using hx {n}')
    w(f'    apply E x')
    for kind in ('a', 'b'):
        w(f'    · intro i')
        w(f'      fin_cases i')
        for i in range(5):
            if [kind, i] in free:
                n = free.index([kind, i])
                w(f'      · exact t{n}')
            else:
                expr, _ = ks[(kind, i)]
                ex = sp.expand(expr)
                comb = ' + '.join(f'{coeff_str(ex.coeff(t[n]))} * t{n}' for n in range(N) if ex.coeff(t[n]) != 0) or '0'
                w(f'      · show {kind} {i} x = 0')
                w(f'        linear_combination d{kind}{i} x + {comb}')
    w(f'  obtain ⟨C, hC, y, hy⟩ := chart {tau} inj hP')
    w(f'  have hCm : C ∈ (Finset.univ : Finset (Fin {N})).powersetCard 3 :=')
    w(f'    Finset.mem_powersetCard.mpr ⟨Finset.subset_univ _, hC⟩')
    charts = list(itertools.combinations(range(N), 3))
    lst = ', '.join('{' + ', '.join(map(str, ch)) + '}' for ch in charts)
    w(f'  rw [show (Finset.univ : Finset (Fin {N})).powersetCard 3 = {{{lst}}} from by decide] at hCm')
    w(f'  simp only [Finset.mem_insert, Finset.mem_singleton] at hCm')
    w(f'  rcases hCm with ' + ' | '.join(['rfl'] * len(charts)))
    for ch in charts:
        cert = next(x for x in cs if tuple(x['C']) == ch)
        w(f'  · -- chart C = {ch}')
        facts = []
        for k in ch:
            for kp in ch:
                nm = f'y{k}_{kp}'
                w(f'    have {nm} : {lean_free[kp]} (y {k}) = {1 if k == kp else 0} := by')
                w(f'      simpa using hy {k} (by decide) {kp} (by decide)')
                facts.append(nm)
        atom = lambda s: (lambda kp, kk: f'{lean_free[int(kp)]} (y {kk})')(*str(s)[1:].split('_'))
        terms = []
        for n, ev in enumerate(cert['evals']):
            pt = ' + '.join(f'({v} : ℂ) • y {k}' for k, v in zip(ch, ev['s']) if v != 0)
            w(f'    have e{n} := M ({pt}) {ev["j"]}')
            w(f'    simp only [g3, Fin.sum_univ_five, {", ".join(dep_names)}, map_add, map_smul,')
            w(f'      smul_eq_mul, {", ".join(facts)}] at e{n}')
            terms.append(f'({poly_str(ev["g"], atom)}) * e{n}')
        w(f'    have one : (1 : ℂ) = 0 := by')
        w(f'      linear_combination ' + ' + '.join(terms))
        w(f'    exact one_ne_zero one')
    w('')

# dispatcher
w('/-- The finite core of vJ: in the branch `∑ b = 0`, dimension at most two. -/')
w('theorem core (a b : Fin 5 → P →ₗ[ℂ] ℂ)')
w('    (E : ∀ x, (∀ i, a i x = 0) → (∀ i, b i x = 0) → x = 0)')
w('    (hb : ∀ x, ∑ j, b j x = 0)')
w('    (hS : ∀ i, b i = 0 ∨ ∀ x, 2 * a i x = ∑ j, a j x)')
w('    (M : ∀ x j, g3 j (fun i => a i x) + g3 j (fun i => b i x) = 0) :')
w('    finrank ℂ P ≤ 2 := by')
w('  by_contra hP')
w('  replace hP : 2 < finrank ℂ P := by omega')
w('  rcases hS 0 with h0 | h0 <;> rcases hS 1 with h1 | h1 <;> rcases hS 2 with h2 | h2 <;>')
w('    rcases hS 3 with h3 | h3 <;> rcases hS 4 with h4 | h4')
names = []
for g in range(32):
    bs = ''.join(str(g >> (4 - i) & 1) for i in range(5))
    names.append(f'case_{bs} a b E hb h0 h1 h2 h3 h4 M hP')
w('  exacts [' + ',\n    '.join(names) + ']')
w('')
w('end PEqualNP.Gct.Scratch219.VJ')
open(OUT, 'w').write('\n'.join(L) + '\n')
print('wrote', OUT, len(L), 'lines')
